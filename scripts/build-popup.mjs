// Dependency-free bundle: a single deferred script avoids chained module loads.
// The readable modules remain the source of truth; only popup.js is shipped.
import { readFile, writeFile } from 'node:fs/promises';
const extension = new URL('../extension/', import.meta.url);
export async function buildPopupSource() {
  const sources = await Promise.all(['core.mjs', 'i18n.mjs', 'popup.mjs'].map(async filename => {
    const source = (await readFile(new URL(filename, extension), 'utf8')).replace(/\r\n/gu, '\n');
    const body = source.replace(/^import [^\n]+;\n/gmu, '').replace(/^export (?=(?:const|function|async function)\b)/gmu, '');
    if (/^(?:import|export)\s/gmu.test(body)) throw new Error(`Unsupported module syntax in ${filename}`);
    return `// Source: ${filename}\n${body.trim()}\n`;
  }));
  return `// Generated by scripts/build-popup.mjs. Edit the .mjs source files.\n(async function () {\n'use strict';\n${sources.join('\n')}\n})();\n`;
}
if (process.argv[1]?.endsWith('build-popup.mjs')) {
  const source = await buildPopupSource();
  await writeFile(new URL('popup.js', extension), source);
  console.log(`Built popup.js: ${Buffer.byteLength(source)} bytes, no external dependencies.`);
}
